const mappings = require('./legacyArticlePaths.json')

function buildLegacyRedirects(paths = mappings) {
  return Object.entries(paths).sort(([a], [b]) => a.localeCompare(b)).map(([source, destination]) => {
    if (!/^\/article\/lofter-[a-z0-9-]+$/.test(source) ||
        !/^\/[a-z0-9-]+\/lofter-[a-z0-9-]+$/.test(destination) || source === destination ||
        source.split('/').at(-1) !== destination.split('/').at(-1)) {
      throw new Error(`Invalid legacy article redirect: ${source}`)
    }
    return { source, destination, permanent: true }
  })
}

function netlifyRedirects(paths = mappings, locales = ['zh-CN']) {
  const rules = buildLegacyRedirects(paths)
  const lines = ['# Generated by scripts/generate-danbouru-redirects.cjs; exact public LOFTER aliases only.']
  for (const { source, destination } of rules) {
    lines.push(`${source} ${destination} 301`)
    for (const locale of locales) {
      if (!/^[a-zA-Z0-9-]+$/.test(locale)) throw new Error('Invalid locale')
      lines.push(`/${locale}${source} /${locale}${destination} 301`)
    }
  }
  return lines.join('\n') + '\n'
}

module.exports = { buildLegacyRedirects, netlifyRedirects }
